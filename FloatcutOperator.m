	return [clippingStore jcListCount];
}

-(int)rememberNum
{
	return [clippingStore rememberNum];
}

-(int)stackPosition
{
	return stackPosition;
}

-(bool)setStackPositionToFirstItem
{
	if ( [clippingStore jcListCount] > 0 ) {
		stackPosition = 0;
		return YES;
	}
	return NO;
}

-(bool)setStackPositionToLastItem
{
	if ( [clippingStore jcListCount] > 0 ) {
		stackPosition = [clippingStore jcListCount] - 1;
		return YES;
	}
	return NO;
}

-(bool)setStackPositionToTenMoreRecent
{
	if ( [clippingStore jcListCount] > 0 ) {
		stackPosition = stackPosition - 10; if ( stackPosition < 0 ) stackPosition = 0;
		return YES;
	}
	return NO;
}

-(bool)setStackPositionToTenLessRecent
{
	if ( [clippingStore jcListCount] > 0 ) {
		stackPosition = stackPosition + 10; if ( stackPosition >= [clippingStore jcListCount] ) stackPosition = [clippingStore jcListCount] - 1;
		return YES;
	}
	return NO;
}

-(bool)clearItemAtStackPosition
{
    if ([clippingStore jcListCount] == 0)
        return NO;

	inhibitAutosaveClippings = YES; // Avoid saving things that the user explicitly deletes.
	[clippingStore clearItem:stackPosition];
	inhibitAutosaveClippings = NO;
	[self actionAfterListModification];

    return YES;
}

-(bool)setStackPositionTo:(int) newStackPosition
{
	if ( [clippingStore jcListCount] >= newStackPosition ) {
		stackPosition = newStackPosition;
		return YES;
	}
	return NO;
}

// Would probably be good to just prevent this scenario where it originates and
// delete this check.
-(void)adjustStackPositionIfOutOfBounds
{
	if (stackPosition >= [clippingStore jcListCount] && stackPosition != 0) { // deleted last item
		stackPosition = [clippingStore jcListCount] - 1;
	}
}

-(bool)stackPositionIsInBounds
{
	return ( [clippingStore jcListCount] > 0 && [clippingStore jcListCount] > stackPosition );
}

-(void)clearList
{
    [clippingStore clearList];
    [self actionAfterListModification];
}

-(void)clearPrimaryList
{
	FloatcutStore *primaryStore = [self favoritesStoreIsSelected] ? stashedStore : clippingStore;
	if (!primaryStore)
		return;

	BOOL previousInhibitAutosave = inhibitAutosaveClippings;
	inhibitAutosaveClippings = YES;
	[primaryStore clearList];
	inhibitAutosaveClippings = previousInhibitAutosave;

	if (primaryStore == clippingStore)
		stackPosition = 0;
	else
		stashedStackPosition = 0;
	[self actionAfterListModification];
}

-(void)clearFavoritesList
{
	BOOL previousInhibitAutosave = inhibitAutosaveClippings;
	inhibitAutosaveClippings = YES;
	[favoritesStore clearList];
	inhibitAutosaveClippings = previousInhibitAutosave;

	if ([self favoritesStoreIsSelected])
		stackPosition = 0;
	else
		favoritesStackPosition = 0;
	[self actionAfterListModification];
}

-(void)mergeList
{
	[clippingStore mergeList];
	[self actionAfterListModification];
}

-(BOOL) isValidClippingNumber:(NSNumber *)number {
	return [self isValidClippingNumber:number inStore:clippingStore];
}

-(BOOL) isValidClippingNumber:(NSNumber *)number inStore:(FloatcutStore*)store {
    return ( ([number intValue] + 1) <= [store jcListCount] );
}

-(NSString *) clippingStringWithCount:(int)count {
	return [self clippingStringWithCount:count inStore:clippingStore];
}

-(NSString *) clippingStringWithCount:(int)count inStore:(FloatcutStore*)store {
    if ( [self isValidClippingNumber:[NSNumber numberWithInt:count] inStore:store] ) {
        return [store clippingContentsAtPosition:count];
    } else { // It fails -- we shouldn't be passed this, but...
        return @"";
    }
}

-(bool) loadEngineFrom:(NSDictionary*)loadDict key:(NSString*)listKey into:(FloatcutStore*)store
{
	NSArray *savedJCList = [loadDict objectForKey:listKey];
	if ( [savedJCList isKindOfClass:[NSArray class]] ) {
		// There's probably a nicer way to prevent the range from going out of bounds, but this works.
		int rangeCap = [savedJCList count] < [store rememberNum] ? [savedJCList count] : [store rememberNum];
		NSRange loadRange = NSMakeRange(0, rangeCap);
		NSArray *toBeRestoredClips = [[[savedJCList subarrayWithRange:loadRange] reverseObjectEnumerator] allObjects];
		for( NSDictionary *aSavedClipping in toBeRestoredClips) {
			FloatcutClipping *clipping = [[FloatcutClipping alloc] initWithContents:[aSavedClipping objectForKey:@"Contents"] ?: @""
														withType:[aSavedClipping objectForKey:@"Type"] ?: @""
												   withImageData:[aSavedClipping objectForKey:@"ImageData"]
											   withDisplayLength:[store displayLen]
											withAppLocalizedName:[aSavedClipping objectForKey:@"AppLocalizedName"]
												withAppBundleURL:[aSavedClipping objectForKey:@"AppBundleURL"]
											   withTimestamp:[[aSavedClipping objectForKey:@"Timestamp"] integerValue]];
			[clipping setIdentifier:[aSavedClipping objectForKey:@"Identifier"]];
			NSNumber *receivedFromSync = [aSavedClipping objectForKey:@"ReceivedFromSync"];
			NSString *savedAppName = [clipping appLocalizedName] ?: @"";
			[clipping setReceivedFromSync:receivedFromSync
				? [receivedFromSync boolValue]
				: [savedAppName hasPrefix:@"Sync: "]];
			// Preserve the previous loader's empty-text filtering while allowing
			// image clippings, whose textual contents are intentionally empty.
			if ([clipping isImage] || [[clipping contents] length] > 0)
				[store addClipping:clipping];
			[clipping release];
		}
		return YES;
	} else DLog(@"Not array");
	return NO;
}

-(bool) loadEngineFromPList
{
	NSDictionary *loadDict = [[[NSUserDefaults standardUserDefaults] dictionaryForKey:@"store"] copy];

	if ( loadDict != nil ) {
		bool success = NO;
		success |= [self loadEngineFrom:loadDict key:@"jcList" into:clippingStore];
		success |= [self loadEngineFrom:loadDict key:@"favoritesList" into:favoritesStore];
		[loadDict release];
		return success;
	}
	return NO;
}

-(bool)setStackPositionToOneLessRecent
{
	stackPosition++;
	if ( [clippingStore jcListCount] > stackPosition ) {
		return YES;
	} else {
		if ( [[NSUserDefaults standardUserDefaults] boolForKey:@"wraparoundBezel"] ) {
			stackPosition = 0;
			return YES;
		} else {
			stackPosition--;
		}
	}
	return NO;
}

-(bool)setStackPositionToOneMoreRecent
{
	stackPosition--;
	if ( stackPosition < 0 ) {
		if ( [[NSUserDefaults standardUserDefaults] boolForKey:@"wraparoundBezel"] ) {
			stackPosition = [clippingStore jcListCount] - 1;
			return YES;
		} else {
			stackPosition = 0;
			return NO;
		}
	}
	if ( [clippingStore jcListCount] > stackPosition ) {
		return YES;
	}
	return NO;
}

-(FloatcutClipping*)clippingAtStackPosition
{
    return [clippingStore clippingAtPosition:stackPosition];
}

- (void)saveStore:(FloatcutStore *)store toKey:(NSString *)key onDict:(NSMutableDictionary *)saveDict previousDict:(NSDictionary *)previousDict {
	if (![store modifiedSinceLastSaveStore]) {
		NSArray *previousArray = [previousDict objectForKey:key];
		[saveDict setObject:previousArray ?: [NSArray array] forKey:key];
		return;
	}

    NSMutableArray *jcListArray = [NSMutableArray array];
    for ( int i = 0 ; i < [store jcListCount] ; i++ )
    {
        FloatcutClipping *clipping = [store clippingAtPosition:i];
        NSMutableDictionary *dict = [NSMutableDictionary dictionaryWithObjectsAndKeys:
                                     [clipping contents], @"Contents",
                                     [clipping type], @"Type",
                                     [NSNumber numberWithInt:i], @"Position",nil];

		NSString *val = [clipping appLocalizedName];
        if ( nil != val )
            [dict setObject:val forKey:@"AppLocalizedName"];

        val = [clipping appBundleURL];
        if ( nil != val )
            [dict setObject:val forKey:@"AppBundleURL"];

        NSData *imageData = [clipping imageData];
        if ( nil != imageData )
            [dict setObject:imageData forKey:@"ImageData"];

        int timestamp = [clipping timestamp];
		if ( timestamp > 0 )
			[dict setObject:[NSNumber numberWithInt:timestamp] forKey:@"Timestamp"];

		val = [clipping identifier];
		if ([val length] > 0)
			[dict setObject:val forKey:@"Identifier"];

		if ([clipping receivedFromSync])
			[dict setObject:[NSNumber numberWithBool:YES] forKey:@"ReceivedFromSync"];

        [jcListArray addObject:dict];
    }
    [saveDict setObject:jcListArray forKey:key];
	[store clearModifiedSinceLastSaveStore];
}

-(void) saveEngine {
    [NSObject cancelPreviousPerformRequestsWithTarget:self selector:@selector(runDeferredSaveEngine) object:nil];
    pendingDeferredSave = NO;

	// saveEngine saves to NSUserDefaults.  If there have been no modifications, just skip this to avoid busy activity for any observers.
	if ( !([clippingStore modifiedSinceLastSaveStore]
		   || [favoritesStore modifiedSinceLastSaveStore]) )
		return;

#if FLOATCUT_PERFORMANCE_TESTING
    NSTimeInterval snapshotStart = [NSProcessInfo processInfo].systemUptime;
#endif

	NSMutableDictionary *saveDict;
    saveDict = [NSMutableDictionary dictionaryWithCapacity:3];
    [saveDict setObject:@"0.7" forKey:@"version"];
    [saveDict setObject:[NSNumber numberWithInt:[[NSUserDefaults standardUserDefaults] integerForKey:@"rememberNum"]]
                 forKey:@"rememberNum"];
    [saveDict setObject:[NSNumber numberWithInt:[[NSUserDefaults standardUserDefaults] integerForKey:@"favoritesRememberNum"]]
                 forKey:@"favoritesRememberNum"];

	[saveTarget performSelector:saveSelector withObject:saveDict];

	NSDictionary *previousDict = [[NSUserDefaults standardUserDefaults] dictionaryForKey:@"store"];
	[self saveStore:clippingStore toKey:@"jcList" onDict:saveDict previousDict:previousDict];
	[self saveStore:favoritesStore toKey:@"favoritesList" onDict:saveDict previousDict:previousDict];

#if FLOATCUT_PERFORMANCE_TESTING
    NSTimeInterval snapshotEnd = [NSProcessInfo processInfo].systemUptime;
#endif
	[[NSUserDefaults standardUserDefaults] setObject:saveDict forKey:@"store"];
#if FLOATCUT_PERFORMANCE_TESTING
    NSTimeInterval defaultsEnd = [NSProcessInfo processInfo].systemUptime;
#endif
	[[NSUserDefaults standardUserDefaults] synchronize];
#if FLOATCUT_PERFORMANCE_TESTING
    NSTimeInterval syncEnd = [NSProcessInfo processInfo].systemUptime;
    NSLog(@"Persistence benchmark: snapshot=%.3f setObject=%.3f synchronize=%.3f total=%.3f ms",
          (snapshotEnd - snapshotStart) * 1000, (defaultsEnd - snapshotEnd) * 1000,
          (syncEnd - defaultsEnd) * 1000, (syncEnd - snapshotStart) * 1000);
#endif
}

- (void)scheduleDeferredSaveEngine
{
    pendingDeferredSave = YES;
    [NSObject cancelPreviousPerformRequestsWithTarget:self selector:@selector(runDeferredSaveEngine) object:nil];
    [self performSelector:@selector(runDeferredSaveEngine)
               withObject:nil
               afterDelay:FloatcutDeferredSaveDelay
                  inModes:@[NSRunLoopCommonModes]];
}

- (void)runDeferredSaveEngine
{
    if (!pendingDeferredSave)
        return;

    pendingDeferredSave = NO;
    [self saveEngine];
}

-(void)prepareForMigrationRestart
{
    [NSObject cancelPreviousPerformRequestsWithTarget:self selector:@selector(runDeferredSaveEngine) object:nil];
    pendingDeferredSave = NO;
    suppressNextTerminationSave = YES;
}

- (void)applicationWillTerminate {
    [NSObject cancelPreviousPerformRequestsWithTarget:self selector:@selector(runDeferredSaveEngine) object:nil];
    pendingDeferredSave = NO;

    if (suppressNextTerminationSave)
        return;

	if ( [[NSUserDefaults standardUserDefaults] integerForKey:@"savePreference"] >= 1 ) {
		DLog(@"Saving on exit");
        [self saveEngine];
    } else {
        // Remove clips from store
        [[NSUserDefaults standardUserDefaults] setValue:[NSDictionary dictionary] forKey:@"store"];
        DLog(@"Saving preferences on exit");
        [[NSUserDefaults standardUserDefaults] synchronize];
    }
}

